"""Parse the Rolling Sprint Capacity workbook and own its rolling-average rule.

`Rolling_Sprint_Capacity.xlsx` is the sheet the team maintains by hand: one column-pair
(Capacity, Actual) per sprint starting at column B, each block's week range in row 5, and
one developer per row from row 7. Two realities make it non-trivial:

1. Capacity cells for sprints 2+ are Excel formulas
   (`=ROUND(AVERAGE(prev_capacity, prev_actual), 0)`) that read back as ``None`` under
   ``data_only=True``, because the workbook is generated by openpyxl and never opened in
   Excel. Capacity is therefore reconstructed by cascading the rule forward from the one
   literal cell, rounding half AWAY from zero to match Excel's ROUND (Python's `round()`
   is half-to-even, which disagrees on every .5).
2. The sheet uses short first names; the roster uses Jira full names — `_ALIAS` bridges them.

This module is pure: it reads a file and computes numbers, never touching the database.
Persistence (import, edit, recompute) lives in app/capacity_store.py.
"""
from __future__ import annotations

import datetime as dt
import math
from collections.abc import Sequence
from dataclasses import dataclass

# Sheet layout, 1-based the way openpyxl addresses cells.
_ROW_WEEKS = 5        # 'Jun 29 - Jul 3' per sprint block
_ROW_FIRST_DEV = 7
_COL_NAMES = 1
_COL_FIRST_BLOCK = 2  # first block's Capacity column; its Actual is the column after
_BLOCK_WIDTH = 2
_TOTAL_LABEL = "TOTAL"

# Capacity-sheet short name -> Jira full name (as it appears in report_assignees).
_ALIAS = {
    "Sidney": "Sidney Buenaventura",
    "Denille": "Deinielle Cruz",
    "Dan": "Dan Denver De Leon",
    "Rudolf": "Dan Rudolf",
    "Allen": "Allen Mathew Cordero",
    "Shane": "Shane Michael Singwa",
    "PAM": "Pamela Denisse Sacdalan",
    "Muscan": "Muskan Dawar",
    "Muskan": "Muskan Dawar",
}

_MONTHS = {
    "Jan": 1, "Feb": 2, "Mar": 3, "Apr": 4, "May": 5, "Jun": 6,
    "Jul": 7, "Aug": 8, "Sep": 9, "Oct": 10, "Nov": 11, "Dec": 12,
}


@dataclass(frozen=True)
class DeveloperRow:
    """One developer's line in the sheet: their seed capacity plus one actual per block."""

    name: str                   # Jira full name where the alias table knows it
    seed_capacity: int
    actuals: list[int | None]   # same length/order as CapacitySheet.starts


@dataclass(frozen=True)
class CapacitySheet:
    """The parsed workbook — each sprint block's week start, and one row per developer."""

    starts: list[dt.date | None]
    developers: list[DeveloperRow]


def round_half_away(x: float) -> int:
    """Round half away from zero, matching Excel's ROUND (Python's round() is half-even)."""
    return math.floor(x + 0.5) if x >= 0 else math.ceil(x - 0.5)


def next_capacity(previous_capacity: int, previous_actual: int | None) -> int:
    """A sprint's capacity from the sprint before it — the sheet's rolling rule.

    `=ROUND(AVERAGE(prev_capacity, prev_actual), 0)`, with a blank actual carrying the
    capacity forward unchanged (the sheet's `IF(actual="", capacity, …)` guard).
    """
    if previous_actual is None:
        return previous_capacity
    return round_half_away((previous_capacity + previous_actual) / 2)


def cascade(seed: int, actuals: Sequence[int | None]) -> list[int]:
    """One capacity per sprint, rolling `seed` forward through `actuals`.

    The first capacity IS the seed (the only hand-entered one); each later capacity is
    `next_capacity` of the plan/result pair before it. Returns a list as long as `actuals`.
    """
    if not actuals:
        return []
    capacities = [seed]
    for actual in actuals[:-1]:
        capacities.append(next_capacity(capacities[-1], actual))
    return capacities


def read_sheet(path: str, year: int) -> CapacitySheet | None:
    """Parse the capacity workbook, or None when it is missing, unreadable, or not a grid.

    `year` seeds the sheet's year-less week ranges. Everything here is best-effort so a
    renamed or absent workbook degrades to "no sheet" instead of breaking the endpoint.
    """
    try:
        import openpyxl  # imported lazily so a missing dep can't break app import
    except ImportError:
        return None
    try:
        ws = openpyxl.load_workbook(path, data_only=False).active
    except (OSError, ValueError, KeyError):
        return None

    columns = _block_columns(ws)
    starts = _week_starts(ws, columns, year)
    if not any(starts):
        return None
    return CapacitySheet(starts=starts, developers=_developer_rows(ws, columns))


def _block_columns(ws) -> list[int]:
    """Column of each block's Capacity cell (its Actual sits in the very next column)."""
    return list(range(_COL_FIRST_BLOCK, ws.max_column + 1, _BLOCK_WIDTH))


def _week_starts(ws, columns: Sequence[int], year: int) -> list[dt.date | None]:
    """Start date of every sprint block, read from row 5's 'Jul 20 - Jul 24' ranges.

    The sheet omits the year, so `year` seeds it and is bumped whenever a block starts
    earlier than the block before it — the only way the ranges can cross a New Year.
    """
    starts: list[dt.date | None] = []
    latest: dt.date | None = None
    for col in columns:
        raw = ws.cell(_ROW_WEEKS, col).value
        start = _week_start(raw, year)
        if start and latest and start < latest:
            year += 1
            start = _week_start(raw, year)
        latest = start or latest
        starts.append(start)
    return starts


def _week_start(cell_text, year: int) -> dt.date | None:
    """Parse a row-5 range like 'Jul 20 - Jul 24' into its start date for `year`."""
    try:
        month, day = str(cell_text).split("-")[0].strip().split()
        return dt.date(year, _MONTHS[month[:3]], int(day))
    except (ValueError, KeyError, AttributeError):
        return None


def _developer_rows(ws, columns: Sequence[int]) -> list[DeveloperRow]:
    """A row per developer, skipping the TOTAL line, the SUMMARY block and blank spacers."""
    rows: list[DeveloperRow] = []
    for row in range(_ROW_FIRST_DEV, ws.max_row + 1):
        name = _developer_name(ws.cell(row, _COL_NAMES).value)
        seed = _as_count(ws.cell(row, _COL_FIRST_BLOCK).value)
        if name is None or seed is None:
            continue  # TOTAL/SUMMARY rows hold a formula or nothing in the seed cell
        rows.append(DeveloperRow(name=name, seed_capacity=seed, actuals=_actuals(ws, row, columns)))
    return rows


def _developer_name(raw) -> str | None:
    """The Jira full name for a sheet row label, or None when the row isn't a developer."""
    text = str(raw or "").strip()
    if not text or text.upper() == _TOTAL_LABEL:
        return None
    return _ALIAS.get(text, text)


def _actuals(ws, row: int, columns: Sequence[int]) -> list[int | None]:
    """The developer's typed Actual for each sprint block (None wherever it's still blank)."""
    return [_as_count(ws.cell(row, col + 1).value) for col in columns]


def _as_count(value) -> int | None:
    """A typed ticket count, or None for a blank cell or an unevaluated formula string."""
    return value if isinstance(value, int) and not isinstance(value, bool) else None
